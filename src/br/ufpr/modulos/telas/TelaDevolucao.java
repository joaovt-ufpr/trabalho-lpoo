    private void btnDevolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDevolverActionPerformed
        int linhaSelecionada = tabelaLocacoes.getSelectedRow();

         if (linhaSelecionada == -1) {
             javax.swing.JOptionPane.showMessageDialog(
                 this,
                 "Selecione uma locação para devolver."
             );
             return;
         }

         VeiculoI veiculo = modeloTabela.getVeiculo(linhaSelecionada);

         Object[] opcoes = {"Sim", "Não"};
         int confirmacao = javax.swing.JOptionPane.showOptionDialog(
             this,
             "Confirma a devolução do veículo " + veiculo.getPlaca() + "?",
             "Confirmar devolução",
             javax.swing.JOptionPane.YES_NO_OPTION,
             javax.swing.JOptionPane.QUESTION_MESSAGE,
             null,
             opcoes,
             opcoes[0]
         );

         if (confirmacao == 0) {

             veiculo.devolver();
             atualizarListaLocacoes();

             javax.swing.JOptionPane.showMessageDialog(
                 this,
                 "Veículo devolvido com sucesso!"
             );

     }
    }//GEN-LAST:event_btnDevolverActionPerformed

